bool initDisplays(void) {
  // Inicializar ambos buses I2C físicos independientes
  Wire.begin(DESK_OLED_LEFT_SDA_GPIO, DESK_OLED_LEFT_SCL_GPIO);
  Wire1.begin(DESK_OLED_RIGHT_SDA_GPIO, DESK_OLED_RIGHT_SCL_GPIO);

  // Iniciar pantalla superior (Dirección 0x3C en Wire)
  if(!oledIzquierdo.begin(SSD1306_SWITCHCAPVCC, DESK_OLED_I2C_ADDRESS)) {
    Serial.println(F("Error crítico: No se detecta la OLED Izquierda"));
    return false;
  }

  // Iniciar pantalla inferior (Dirección 0x3C en Wire1)
  if(!oledDerecho.begin(SSD1306_SWITCHCAPVCC, DESK_OLED_I2C_ADDRESS)) {
    Serial.println(F("Error crítico: No se detecta la OLED Derecha"));
    return false;
  }

  // Limpiar buffers iniciales
  oledIzquierdo.clearDisplay();
  oledDerecho.clearDisplay();
  oledIzquierdo.display();
  oledDerecho.display();
  return true;
}

