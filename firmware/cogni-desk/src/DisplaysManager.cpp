// Función para renderizar el menú interactivo aprovechando las dos pantallas
void mostrarMenuIconos(int opcion) {
  // Pantalla Izquierda: Muestra el Icono Bitmap activo
  oledIzquierdo.clearDisplay();
  oledIzquierdo.drawBitmap(32, 0, iconoTemperatura, 64, 64, SSD1306_WHITE);
  oledIzquierdo.drawRect(0, 0, 128, 64, SSD1306_WHITE); // Marco de selección
  oledIzquierdo.display();

  // Pantalla Derecha: Muestra el texto descriptivo del menú y estado de opción
  oledDerecho.clearDisplay();
  oledDerecho.setTextSize(1);
  oledDerecho.setTextColor(SSD1306_WHITE);
  oledDerecho.setCursor(10, 10);
  oledDerecho.print(F("-- MENU ALBA --"));

  oledDerecho.setCursor(10, 28);
  if (opcion == 0) {
    oledDerecho.println(F("> SENSOR TEMP"));
    oledDerecho.setCursor(10, 45);
    oledDerecho.println(F("  MEDICAMENTOS"));
  } else {
    oledDerecho.println(F("  SENSOR TEMP"));
    oledDerecho.setCursor(10, 45);
    oledDerecho.println(F("> MEDICAMENTOS"));
  }
  oledDerecho.display();
}