void mostrarOjosALBA() {
// --- OLEDIZQUIERDO (Ojo izquierdo + barra hacia la derecha) ---
  oledIzquierdo.clearDisplay();
  
  // Dibujar óvalo/ojo izquierdo (x, y, ancho, alto, radio de esquina)
  oledIzquierdo.fillRoundRect(60, 16, 28, 32, 12, SSD1306_WHITE);
  
  // Línea horizontal central que sale hacia el borde derecho (conectando con la otra pantalla)
  // Dibujamos 3 líneas juntas para darle grosor de "barra metálica"
  oledIzquierdo.drawLine(88, 31, 127, 31, SSD1306_WHITE);
  oledIzquierdo.drawLine(88, 32, 127, 32, SSD1306_WHITE);
  oledIzquierdo.drawLine(88, 33, 127, 33, SSD1306_WHITE);
  
  oledIzquierdo.display();

  // --- OLEDDERECHO (Barra desde la izquierda + ojo derecho) ---
  oledDerecho.clearDisplay();
  
  // Línea horizontal que entra desde el borde izquierdo
  oledDerecho.drawLine(0, 31, 40, 31, SSD1306_WHITE);
  oledDerecho.drawLine(0, 32, 40, 32, SSD1306_WHITE);
  oledDerecho.drawLine(0, 33, 40, 33, SSD1306_WHITE);

  // Dibujar óvalo/ojo derecho
  oledDerecho.fillRoundRect(40, 16, 28, 32, 12, SSD1306_WHITE);
  
  oledDerecho.display();
}
